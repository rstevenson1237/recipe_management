#!/usr/bin/env node
/**
 * Exercises the PDF-parsing functions inside Import.html against synthetic pdf.js output.
 *
 * Those parsers are the one piece of this project with real logic that can be run outside
 * the Apps Script/browser runtime: they turn pdf.js text runs into recipes, and every
 * interesting case (a two-column page where an ingredient and an instruction share a
 * baseline, a v1 PDF whose commas must not be read as preparations, an overflow page) is
 * invisible until a PDF actually goes wrong in front of a user.
 *
 * Like scripts/typecheck.js, this works by copying source the editor owns into a
 * gitignored .typecheck/ dir: the <script> block of Import.html is written out as a CommonJS
 * module with browser globals stubbed, then required here. Nothing is modified in place.
 */

const assert = require('assert');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, '.typecheck');
const OUT_FILE = path.join(OUT_DIR, 'import-parsers.js');

const EXPORTED = [
  'parseDataBlocks', 'parsePrintedLayout', 'groupIntoLines', 'parseIngredientLine',
  'splitNameAndPrep', 'parseStepLines', 'splitQtyUom', 'metaValue', 'detectVersion',
  'isNoiseLine', 'bodyLines', 'recipeTitle', 'decodeBase64Utf8', 'columnSplitX'
];

function extractParsers() {
  const html = fs.readFileSync(path.join(ROOT, 'Import.html'), 'utf8');
  const open = html.lastIndexOf('<script>');
  const close = html.lastIndexOf('</script>');
  if (open === -1 || close === -1 || close < open) {
    throw new Error("Import.html has no trailing <script> block - can't extract the parsers.");
  }

  const source = [
    '// Generated by scripts/test-import-parsers.js from Import.html - do not edit.',
    'const document = {};',
    'const window = { pdfjsLib: { GlobalWorkerOptions: {} } };',
    'const pdfjsLib = window.pdfjsLib;',
    'const Vue = { createApp: () => ({ mount: () => {} }) };',
    'const google = { script: { run: {} } };',
    'const atob = (s) => Buffer.from(s, "base64").toString("binary");',
    'const { TextDecoder } = require("util");',
    html.slice(open + '<script>'.length, close),
    'module.exports = { ' + EXPORTED.join(', ') + ' };'
  ].join('\n');

  fs.mkdirSync(OUT_DIR, { recursive: true });
  fs.writeFileSync(OUT_FILE, source);
  return require(OUT_FILE);
}

// --- fixtures -------------------------------------------------------------------------

const HELPER_ITEMS = ['Chives', 'Butter', 'Salt, kosher'];
const HELPER_UOMS = ['GRM', 'OZ-wt', 'LB', 'tsp', 'Tbsp', 'Cup', 'Each'];

function item(str, x, y, height) {
  return { str: str, x: x, y: y, height: height };
}

/**
 * One page of text runs laid out the way Export.html prints a recipe: meta grid on top,
 * the two body columns side by side - so ingredient and instruction runs deliberately
 * SHARE y values, which is what makes the column split load-bearing - footer bottom right.
 */
function page(options) {
  const o = Object.assign({ name: 'Chive Butter', version: 2, dataBlock: null, prep: 'minced' }, options);
  const items = [];

  if (o.name) items.push(item(o.name, 36, 740, 22));
  items.push(
    item('Measure Type:', 36, 715, 12), item('Weight', 110, 715, 12),
    item('Yield:', 200, 715, 12), item('5 LB', 240, 715, 12),
    item('Reporting U of M:', 320, 715, 12), item('LB', 430, 715, 12),
    item('Portion:', 36, 700, 12), item('1 OZ-wt', 100, 700, 12),
    item('In Inventory:', 200, 700, 12), item('Yes', 280, 700, 12),
    item('Inventory U of M:', 320, 700, 12), item('LB', 430, 700, 12),
    item('Ingredients', 36, 650, 13), item('Instructions', 250, 650, 13),
    item('1 Tbsp — Chives' + (o.prep ? ', ' + o.prep : ''), 36, 630, 13),
    item('1.', 250, 630, 13), item('Soften the butter', 266, 630, 13),
    item('8 OZ-wt — Butter', 36, 612, 13),
    item('2.', 250, 612, 13), item('Fold in the chives and', 266, 612, 13),
    item('season to taste', 266, 596, 13), // wrapped continuation of step 2
    item('1 tsp — Salt, kosher', 36, 594, 13)
  );

  if (o.dataBlock) {
    // The printed block wraps over several tiny runs, exactly as the .rm-data div does.
    o.dataBlock.match(/.{1,60}/g).forEach(function(chunk, i) {
      items.push(item(chunk, 36, 120 - i * 7, 5));
    });
  }
  items.push(item('Recipe 1 of 1 · Export v' + o.version, 480, 60, 11));
  return items;
}

/** Same envelope Export.gs's buildRecipeDataBlock_() prints. */
function dataBlock(payload) {
  return 'RMDATA1[' + Buffer.from(JSON.stringify(payload), 'utf8').toString('base64') + ']';
}

const EXPORTED_RECIPE = {
  v: 2, n: 'Chive Butter', mt: 'Weight', ru: 'LB', yq: 5, yu: 'LB',
  wq: 5, wu: 'LB', vq: '', vu: '', eq: '', eu: '',
  ps: 1, pu: 'OZ-wt', inv: 'Yes', iu: 'LB',
  ing: [['Chives', 1, 'Tbsp', 'minced'], ['Butter', 8, 'OZ-wt', ''], ['Salt, kosher', 1, 'tsp', '']],
  st: ['Soften the butter', 'Fold in the chives and season to taste']
};

// --- assertions -----------------------------------------------------------------------

function main() {
  const P = extractParsers();
  let passed = 0;

  function ok(message) {
    passed++;
    console.log('OK: ' + message);
  }

  // 1. Data block: the exact path, which is what makes an export->import round trip lossless.
  let rows = P.parseDataBlocks([page({ dataBlock: dataBlock(EXPORTED_RECIPE) })]);
  assert.strictEqual(rows.length, 1, 'one recipe from the data block');
  assert.strictEqual(rows[0].recipe.name, 'Chive Butter');
  assert.strictEqual(rows[0].recipe.yieldQty, 5, 'quantities stay numbers');
  assert.strictEqual(rows[0].recipe.portionUom, 'OZ-wt');
  assert.strictEqual(rows[0].recipe.inventoryYesNo, 'Yes');
  assert.deepStrictEqual(rows[0].recipe.ingredients[0], { name: 'Chives', qty: 1, uom: 'Tbsp', prep: 'minced' });
  assert.deepStrictEqual(rows[0].recipe.ingredients[2], { name: 'Salt, kosher', qty: 1, uom: 'tsp', prep: '' });
  assert.deepStrictEqual(rows[0].recipe.steps, EXPORTED_RECIPE.st);
  assert.strictEqual(rows[0].source, 'data block (v2)');
  ok('a data block round-trips every field, including a comma inside an ingredient name');

  rows = P.parseDataBlocks([
    page({ dataBlock: dataBlock(EXPORTED_RECIPE) }),
    page({ dataBlock: dataBlock(Object.assign({}, EXPORTED_RECIPE, { n: 'Garlic Butter' })) })
  ]);
  assert.deepStrictEqual(rows.map(function(r) { return r.recipe.name; }), ['Chive Butter', 'Garlic Butter']);
  ok('every data block in a multi-recipe PDF is read, in page order');

  assert.strictEqual(P.parseDataBlocks([[item('RMDATA1[bm90YmFzZTY0anNvbg==]', 36, 100, 5)]]).length, 0);
  ok('an undecodable data block is skipped rather than failing the whole file');

  // 2. Printed layout: the fallback for PDFs with no data block (export v1).
  rows = P.parsePrintedLayout([page({ dataBlock: null, version: 2 })], HELPER_ITEMS, HELPER_UOMS);
  assert.strictEqual(rows.length, 1, 'one recipe from the printed layout');
  let recipe = rows[0].recipe;
  assert.strictEqual(recipe.name, 'Chive Butter');
  assert.strictEqual(recipe.measureType, 'Weight');
  assert.strictEqual(recipe.yieldQty, '5');
  assert.strictEqual(recipe.yieldUom, 'LB');
  assert.strictEqual(recipe.reportingUom, 'LB');
  assert.strictEqual(recipe.portionSize, '1');
  assert.strictEqual(recipe.portionUom, 'OZ-wt');
  assert.strictEqual(recipe.inventoryYesNo, 'Yes');
  assert.strictEqual(recipe.inventoryUom, 'LB');
  ok('the printed meta grid parses into the right fields');

  assert.deepStrictEqual(recipe.ingredients, [
    { name: 'Chives', qty: '1', uom: 'Tbsp', prep: 'minced' },
    { name: 'Butter', qty: '8', uom: 'OZ-wt', prep: '' },
    { name: 'Salt, kosher', qty: '1', uom: 'tsp', prep: '' }
  ]);
  ok('ingredients parse per column even though the columns share baselines');

  assert.deepStrictEqual(recipe.steps, ['Soften the butter', 'Fold in the chives and season to taste']);
  ok('numbered steps parse and a wrapped line rejoins its step');

  rows = P.parsePrintedLayout([page({ dataBlock: null, version: 1, prep: 'minced' })], HELPER_ITEMS, HELPER_UOMS);
  assert.strictEqual(rows[0].source, 'printed layout (v1)');
  assert.deepStrictEqual(rows[0].recipe.ingredients[0], { name: 'Chives, minced', qty: '1', uom: 'Tbsp', prep: '' });
  ok('a v1 PDF never invents a Preparation out of a comma');

  // 3. Name/Preparation splitting - the ambiguity the version stamp and Helper Data resolve.
  assert.deepStrictEqual(P.splitNameAndPrep('Salt, kosher', HELPER_ITEMS), { name: 'Salt, kosher', prep: '' });
  assert.deepStrictEqual(P.splitNameAndPrep('Salt, kosher, cracked', HELPER_ITEMS), { name: 'Salt, kosher', prep: 'cracked' });
  assert.deepStrictEqual(P.splitNameAndPrep('Butter, softened, cubed', HELPER_ITEMS), { name: 'Butter', prep: 'softened, cubed' });
  assert.deepStrictEqual(P.splitNameAndPrep('Shallots, brunoise', HELPER_ITEMS), { name: 'Shallots', prep: 'brunoise' });
  ok('a known ingredient name wins over comma position when splitting off a preparation');

  assert.deepStrictEqual(P.parseIngredientLine('Just Butter', 2, HELPER_ITEMS),
      { name: 'Just Butter', qty: '', uom: '', prep: '' });
  ok('an ingredient line printed without a separator keeps its whole text as the name');

  // 4. Noise, overflow pages, missing fields.
  assert.ok(P.isNoiseLine('Recipe 3 of 12 · Export v2'));
  assert.ok(P.isNoiseLine('RMDATA1[abc]'));
  assert.ok(P.isNoiseLine('eyJ2IjoyLCJuIjoiQ2hpdmUgQnV0dGVyIiwibXQiOiJXZWlnaHQiLCJydSI6IkxCIn0='));
  assert.ok(!P.isNoiseLine('1 Tbsp — Chives, minced'));
  ok('the page footer and the machine-readable block are treated as noise');

  const overflowPage = [
    item('Ingredients', 36, 650, 13), item('Instructions', 250, 650, 13),
    item('3.', 250, 630, 13), item('Chill before serving', 266, 630, 13),
    item('Recipe 1 of 1 · Export v2', 480, 60, 11)
  ];
  rows = P.parsePrintedLayout([page({ dataBlock: null }), overflowPage], HELPER_ITEMS, HELPER_UOMS);
  assert.strictEqual(rows.length, 1, 'a page with no meta grid is an overflow page, not a new recipe');
  assert.deepStrictEqual(rows[0].recipe.steps,
      ['Soften the butter', 'Fold in the chives and season to taste', 'Chill before serving']);
  ok('an overflow page is appended to the recipe it continues');

  const sparsePage = [
    item('Mystery Sauce', 36, 740, 22),
    item('Measure Type:', 36, 715, 12), item('Volume', 110, 715, 12),
    item('Ingredients', 36, 650, 13), item('Instructions', 250, 650, 13),
    item('1.', 250, 630, 13), item('No instructions on file.', 266, 630, 13),
    item('No ingredients on file.', 36, 630, 13)
  ];
  rows = P.parsePrintedLayout([sparsePage], HELPER_ITEMS, HELPER_UOMS);
  assert.strictEqual(rows.length, 1);
  assert.strictEqual(rows[0].recipe.name, 'Mystery Sauce');
  assert.strictEqual(rows[0].recipe.yieldQty, '', 'a missing field degrades to empty, not to a failure');
  assert.deepStrictEqual(rows[0].recipe.ingredients, []);
  assert.deepStrictEqual(rows[0].recipe.steps, []);
  ok('missing fields and the empty-section placeholders degrade gracefully');

  console.log('\nimport parsers: OK - ' + passed + ' assertion group(s) passed.');
}

try {
  main();
} catch (error) {
  console.error('\nimport parsers: FAILED');
  console.error(error && error.message ? error.message : error);
  if (error && error.actual !== undefined) {
    console.error('actual:   ' + JSON.stringify(error.actual));
    console.error('expected: ' + JSON.stringify(error.expected));
  }
  process.exit(1);
}
